# PromptSimplifier — converts tagged prompts to natural language for non-LLM models
# ============================================================================


class PromptSimplifier:
    """Convert [ROLE][TASK][STYLE] tagged prompts into clean natural language
    that image/video generation models actually understand.

    Supports different provider modes:
    - "full" (default): all detail — for LLM-based image models (SiliconFlow, SD)
    - "concise": stripped natural language — for non-LLM models (Agnes)
    - "minimal": short keyword-driven — for fast/cheap providers
    """

    # Provider modes and their characteristics
    _MODE_INSTRUCTIONS: dict[str, dict] = {
        "full": {"max_img_chars": 500, "max_vid_chars": 800, "desc": "LLM-based (SiliconFlow/SD)"},
        "concise": {"max_img_chars": 300, "max_vid_chars": 500, "desc": "non-LLM (Agnes/API)"},
        "minimal": {"max_img_chars": 200, "max_vid_chars": 350, "desc": "keyword-only (fast/cheap)"},
    }

    @staticmethod
    def _detect_provider_mode(provider_name: str = "") -> str:
        """Auto-detect simplification mode from provider name."""
        name = provider_name.lower()
        if "agnes" in name:
            return "concise"
        if "kling" in name:
            return "concise"
        if "comfyui" in name:
            return "full"
        if "volcengine" in name:
            return "concise"
        return "full"  # default

    @staticmethod
    def _build_natural_prompt(
        subject: str,
        style_lines: list[str],
        motion: str = "",
        constraints: str = "",
        prompt_type: str = "image",
        max_chars: int = 500,
    ) -> str:
        """Build a clean natural-language prompt from extracted components.

        Applies Critical Rules from storyboard-prompt-engine:
        - [主体] + [动作] + [场景] + [运镜] + [风格] + [约束]
        - One main motion only
        - No contradictory instructions
        - Constraints always include no-text/no-watermark
        """
        # Keep framing first, so provider length limits cannot remove the ratio.
        parts = [_frame_description(), subject.strip()]

        # Style (lighting + color + mood)
        if style_lines:
            parts.append(', '.join(style_lines))

        # Motion (video only)
        if motion.strip():
            parts.append(f"Camera: {motion.strip()}")
        elif prompt_type == "video":
            parts.append("Camera: locked-off stable shot")

        # Quality and constraints
        quality = "smooth cinematic motion, stable frame, professional quality"
        if constraints:
            quality += f", {constraints}"
        else:
            quality += ", no watermark, no text, no blank frames, no flicker, no distortion"
        parts.append(quality)

        prompt = '. '.join(parts)
        # Clean up
        prompt = re.sub(r'\s+', ' ', prompt)
        prompt = re.sub(r'[。．]\.?', '.', prompt)
        prompt = re.sub(r'\.\s*\.', '.', prompt)
        prompt = re.sub(r'\b(\w+)\s+\1\b', r'\1', prompt, flags=re.IGNORECASE)
        prompt = prompt.strip().rstrip('.') + '.'

        if len(prompt) > max_chars:
            prompt = prompt[:max_chars - 3] + '.'

        return prompt

    @staticmethod
    def simplify_image_prompt(tagged: str, provider_name: str = "") -> str:
        """Strip [TAG] markers and reconstruct a natural-language image prompt.

        Applies Critical Rules:明确主体→动作→环境→运镜→风格→约束的6要素闭环
        """
        mode = PromptSimplifier._detect_provider_mode(provider_name)
        max_chars = PromptSimplifier._MODE_INSTRUCTIONS[mode]["max_img_chars"]

        # Remove the [中文场景] prefix content
        tagged = re.sub(r'\[中文场景\][^.]*\.\s*', '', tagged)

        # Extract content from each section
        task_match = re.search(r'\[TASK\](.*?)(?=\[STYLE\]|$)', tagged, re.DOTALL)
        task_content = task_match.group(1).strip() if task_match else ""

        comp_match = re.search(r'\[COMPOSITION\](.*?)(?=\[CONSTRAINTS\]|$)', tagged, re.DOTALL)
        comp_content = comp_match.group(1).strip() if comp_match else ""

        style_match = re.search(r'\[STYLE\](.*?)(?=\[COMPOSITION\]|$)', tagged, re.DOTALL)
        style_content = style_match.group(1).strip() if style_match else ""

        constraints_match = re.search(r'\[CONSTRAINTS\](.*?)(?=\[FALLBACK\]|$)', tagged, re.DOTALL)
        constraints_content = constraints_match.group(1).strip() if constraints_match else ""

        # Clean style anchor
        style_clean = re.sub(r'\[GLOBAL STYLE ANCHOR[^\]]*\]', '', style_content)
        style_clean = re.sub(r'\[END GLOBAL STYLE ANCHOR\]', '', style_clean)
        style_lines = []
        for prefix in ["Visual Style:", "Lighting:", "Color Palette:", "Mood:", "Camera Signature:"]:
            m = re.search(re.escape(prefix) + r'\s*([^.]*\.)', style_clean)
            if m:
                val = m.group(1).strip().rstrip('.')
                style_lines.append(val)

        # Extract subject
        subject = task_content
        for prefix in ["Generate a high-quality image of:", "Characters/Products visible:",
                        "Key narrative content to reflect:", "Scene intent:"]:
            subject = re.sub(prefix, '', subject)
        subject = re.sub(r'\s*\|\s*', ', ', subject)

        # Extract constraints
        constraints_safe = constraints_content
        constraints_keep = []
        for marker in ["garbled text", "blank", "black frames", "flicker",
                        "subject deformation", "morphing", "fabricated pricing"]:
            if marker in constraints_safe.lower():
                constraints_keep.append(marker)
        constraint_suffix = ""
        if constraints_keep:
            constraint_suffix = "no " + ", no ".join(constraints_keep[:4])

        return PromptSimplifier._build_natural_prompt(
            subject=subject.strip(),
            style_lines=style_lines,
            constraints=constraint_suffix,
            prompt_type="image",
            max_chars=max_chars,
        )

    @staticmethod
    def simplify_video_prompt(tagged: str, provider_name: str = "") -> str:
        """Convert tagged video prompt to natural language.

        Applies Critical Rules from storyboard-prompt-engine:
        - One main motion per shot (NEVER stack push-in + orbit + handheld)
        - Never use contradictory camera instructions
        - Sound/motion design included
        """
        mode = PromptSimplifier._detect_provider_mode(provider_name)
        max_chars = PromptSimplifier._MODE_INSTRUCTIONS[mode]["max_vid_chars"]

        tagged = re.sub(r'\[中文视频场景\][^.]*\.\s*', '', tagged)

        scene_match = re.search(r'\[SCENE\](.*?)(?=\[STYLE\]|$)', tagged, re.DOTALL)
        scene_content = scene_match.group(1).strip() if scene_match else ""

        style_match = re.search(r'\[STYLE\](.*?)(?=\[MOTION\]|$)', tagged, re.DOTALL)
        style_content = style_match.group(1).strip() if style_match else ""

        motion_match = re.search(r'\[MOTION\](.*?)(?=\[CONSTRAINTS\]|$)', tagged, re.DOTALL)
        motion_content = motion_match.group(1).strip() if motion_match else ""

        constraints_match = re.search(r'\[CONSTRAINTS\](.*?)(?=\[FALLBACK\]|$)', tagged, re.DOTALL)
        constraints_content = constraints_match.group(1).strip() if constraints_match else ""

        # Extract subject
        subject = scene_content
        for prefix in ["Subject:", "Content:", "Narrative:", "Characters/Products:", "Setting:"]:
            subject = re.sub(prefix, '', subject)
        subject = re.sub(r'\s*\|\s*', ', ', subject)

        # Extract motion — enforce Critical Rules: single primary motion
        motion = motion_content
        for prefix in ["Camera:", "Movement:", "Duration:" + r'[\d.]+' + r'\s*s\.?\s*']:
            motion = re.sub(prefix, '', motion)
        motion = re.sub(r'Stable frame.*', '', motion)
        # If multiple motions found, keep only the first (Critical Rules: one main motion)
        motion_parts = [m.strip() for m in motion.split(',') if m.strip()]
        if len(motion_parts) > 1:
            motion = motion_parts[0]  # Keep only primary
            logger.debug("PromptSimplifier: trimmed to single primary motion: '%s'", motion)

        # Extract style
        style_clean = re.sub(r'\[GLOBAL STYLE ANCHOR[^\]]*\]', '', style_content)
        style_clean = re.sub(r'\[END GLOBAL STYLE ANCHOR\]', '', style_clean)
        style_lines = []
        for prefix in ["Visual Style:", "Lighting:", "Color Palette:", "Mood:", "Camera Signature:"]:
            m = re.search(re.escape(prefix) + r'\s*([^.]*\.)', style_clean)
            if m:
                val = m.group(1).strip().rstrip('.')
                style_lines.append(val)

        # Extract constraints
        constraints_safe = constraints_content
        constraints_keep = []
        for marker in ["garbled text", "blank", "black frames", "flicker",
                        "subject deformation", "morphing"]:
            if marker in constraints_safe.lower():
                constraints_keep.append(marker)
        constraint_suffix = ""
        if constraints_keep:
            constraint_suffix = "no " + ", no ".join(constraints_keep[:4])

        return PromptSimplifier._build_natural_prompt(
            subject=subject.strip(),
            style_lines=style_lines,
            motion=motion.strip(),
            constraints=constraint_suffix,
            prompt_type="video",
            max_chars=max_chars,
        )


def generate_scene_plans(
    slides: list[Slide],
    style: str | dict[str, str] = "auto",
    overall_theme: str = "",
    images_per_slide: int = 2,
    language: str = "zh-CN",
    use_script_writer: bool = True,
    use_case: str = "auto",
    total_duration: float = 0.0,
    validate_prompts: bool = True,
    narration_style: str = "direct",
    visual_mode: str = "creative",
    narration_records: dict | None = None,
) -> list[EnhancedScenePlan]:
    """One-shot convenience: holistic understanding → Director → scene plans.

    When *use_script_writer* is True (default), the ScriptWriter first
    analyzes the slides holistically and generates a narrative script.
    The script scenes are then passed to the Director for prompt generation.

    When False, falls back to the original 1:1 per-slide approach.

    When *validate_prompts* is True (default), runs PromptValidator after
    generation and logs quality warnings.

    Args:
        use_case: Customer requirement type — affects narrative structure.
            Options: "auto", "education", "ecommerce", "product-launch",
            "brand-story", "corporate", "academic".
        validate_prompts: Run PromptValidator on all generated prompts.
    """
    from pptx_parser import Slide as _Slide  # noqa

    if visual_mode == "faithful":
        from faithful_plan import build_faithful_plans
        return build_faithful_plans(slides, narration_style, total_duration)
    if visual_mode != "creative":
        raise ValueError("visual_mode must be faithful or creative")

    if use_script_writer:
        # Holistic approach: ScriptWriter → Director
        writer = ScriptWriter(
            slides, language=language, overall_theme=overall_theme,
            use_case=use_case, total_duration=total_duration,
            narration_style=narration_style,
        )
        script = writer.write()
        if narration_records is not None:
            for scene in script.scenes:
                scene.narration_by_slide = {i: narration_records[i]['text'] for i in scene.slide_indices}
                scene.narration_text = ''.join(scene.narration_by_slide.values())
                scene.description = scene.narration_text
                scene.key_points = [u['text'] for i in scene.slide_indices
                    for u in narration_records[i].get('units', []) if u.get('decision') != 'skip']
        director = Director(
            slides, style=style, overall_theme=overall_theme,
            images_per_slide=images_per_slide, script=script,
            narration_style=narration_style,
        )
    else:
        director = Director(
            slides, style=style, overall_theme=overall_theme,
            images_per_slide=images_per_slide,
            narration_style=narration_style,
        )

    plans = director.plan()

    # ── Validation: run PromptValidator on all generated prompts ──
    if validate_prompts:
        validation = PromptValidator.validate_all(plans)
        total = validation["total_slides"]
        img_ok = validation["image_pass_rate"]
        vid_ok = validation["video_pass_rate"]
        logger.info(
            "Prompt validation: image %s passed, video %s passed (total %d slides)",
            img_ok, vid_ok, total,
        )
        # Log each issue/warning at debug level
        for report in validation["reports"]:
            for key in ("image", "video"):
                r = report[key]
                if r["issues"]:
                    logger.debug(
                        "Slide %d %s issues: %s",
                        report["slide"], key, "; ".join(r["issues"]),
                    )
                if r["warnings"]:
                    logger.debug(
                        "Slide %d %s warnings: %s",
                        report["slide"], key, "; ".join(r["warnings"]),
                    )

    return plans
