"""
Prompt Engine – the "Director" for PPT-to-video generation.

Transforms raw slide content into cinematic, cohesive image and video
prompts, applying **prompt-engineer** methodology for maximum quality:

- **ConsistencyEngine** — builds a "Style Bible" across all slides (characters,
  products, scenes, lighting, colour palette) so every generated image/video
  feels like one continuous production.
- **Multi-angle keyframes** — generates multiple image prompts per slide
  (wide, medium, close-up, detail) for richer video composition.
- **Narrative flow** — plans transitions between slides so cuts feel natural.
- **Duration recommendations** — per-slide timing based on content density.
- **PromptValidator** — validates prompt quality, detects regressions, and
  suppresses hallucinations (no fabricated content in prompts).
- **Chain-of-Thought scene design** — progressive reasoning from slide content
  → narrative intent → visual execution.
- **Role-Constraint-Output architecture** — every prompt follows a structured
  template: Role Definition → Task Description → Constraints → Output Format
  → Examples (when applicable) → Fallback Strategy.
"""

