@dataclass
class ScriptScene:
    """
    A narrative scene derived from holistic PPT analysis.

    Unlike the 1:1 slide-to-scene approach, ScriptScenes are generated by
    understanding the overall structure, grouping related slides, and
    creating a proper narrative flow.
    """
    scene_number: int
    act_name: str
    title: str
    description: str
    """Narrative description of what this scene conveys."""
    director_vision: str
    slide_indices: list[int]
    """Original 1-based slide numbers covered by this scene."""
    key_points: list[str]
    suggested_duration_sec: float = 5.0
    characters_in_scene: list[str] = field(default_factory=list)
    setting_name: str = ""
    transition_from_prev: str = "cut"
    narration_style: str = "direct"
    narration_text: str = ""
    narration_by_slide: dict[int, str] = field(default_factory=dict)


@dataclass
class Script:
    """Full narrative script — the result of holistic PPT analysis."""
    title: str
    scenes: list[ScriptScene]
    overall_theme: str = ""
    language: str = "zh-CN"
    """Primary language: 'zh-CN' or 'en'."""

    def total_duration(self) -> float:
        return sum(s.suggested_duration_sec for s in self.scenes)

    def describe(self) -> str:
        """Human-readable script outline."""
        lines = [f"📋 {self.title}", f"  共 {len(self.scenes)} 场戏, 总时长 ~{self.total_duration():.0f}s"]
        for s in self.scenes:
            slides_info = f" [页 {','.join(str(i) for i in s.slide_indices)}]" if s.slide_indices else ""
            lines.append(f"  {s.scene_number}. {s.title} ({s.act_name}){slides_info}")
            lines.append(f"     {s.description[:80]}...")
        return "\n".join(lines)


