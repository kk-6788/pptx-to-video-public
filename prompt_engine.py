# PromptValidator — quality assurance for generated prompts (prompt-engineer)
# ============================================================================


class PromptValidator:
    """Validate generated image/video prompts for quality and safety.

    Features:
    - **Hallucination suppression**: detects fabricated details not in source content.
    - **Format compliance**: checks structure (segments present, proper delimiters).
    - **Quality heuristics**: scores prompts on specificity, actionability, and style fit.
    - **Token efficiency**: flags overly verbose prompts that waste inference tokens.
    - **Critical Rules**: enforces one-motion-per-shot, no contradiction, sound design.
    """

    @dataclass
    class ValidationReport:
        """Result of a prompt validation."""
        prompt_preview: str = ""
        score: float = 0.0            # 0.0–1.0
        issues: list[str] = field(default_factory=list)
        warnings: list[str] = field(default_factory=list)
        passed: bool = False

    # Phrases that suggest a prompt is too vague or generic
    _VAGUE_PATTERNS: list[str] = [
        "professional appearance",
        "generic scene",
        "beautiful background",
        "nice lighting",
        "high quality",
        "beautiful",
        "stunning",
        "gorgeous",
        "incredible",
    ]

    # Hallucination triggers: prompts referencing specifics NOT in source
    _HALLUCINATION_TRIGGERS: list[str] = [
        "price", "pricing", "cost", "$", "¥",
        "available now", "buy now", "order now",
        "limited time", "exclusive offer",
    ]

    # Chinese AIGC markers (from antigravity-awesome-skills humanize-chinese)
    _CHINESE_AI_MARKERS: list[str] = [
        "综上所述",
        "值得注意的是",
        "由此可见",
        "换言之",
        "不可否认的是",
        "具有重要意义",
        "产生了深远影响",
        "发挥着不可替代的作用",
    ]

    @classmethod
    def validate_image_prompt(
        cls,
        prompt: str,
        source_key_points: list[str] | None = None,
    ) -> "PromptValidator.ValidationReport":
        """Validate an image generation prompt (matches new [ROLE]...[FALLBACK] format)."""
        report = cls.ValidationReport(
            prompt_preview=prompt[:120] + ("..." if len(prompt) > 120 else ""),
        )
        issues: list[str] = []
        warnings: list[str] = []

        # --- Structural checks (new [TAG] format) ---
        if "[ROLE]" not in prompt:
            issues.append("缺少 [ROLE] 段落")
        if "[TASK]" not in prompt:
            issues.append("缺少 [TASK] 段落(角色任务)")
        if "[STYLE]" not in prompt:
            issues.append("缺少 [STYLE] 段落(风格规范)")
        if "[COMPOSITION]" not in prompt:
            warnings.append("缺少 [COMPOSITION] 段落(构图信息)")
        if "[CONSTRAINTS]" not in prompt:
            issues.append("缺少 [CONSTRAINTS] 段落(约束条件)")
        if "[FALLBACK]" not in prompt:
            warnings.append("缺少 [FALLBACK] 段落(兜底策略)")

        # --- Quality constraints check ---
        prompt_lower = prompt.lower()
        if "no watermark" not in prompt_lower:
            issues.append("缺少水印约束(no watermark)")
        if "no text" not in prompt_lower:
            warnings.append("缺少文字约束(no text)")
        if "no distorted" not in prompt_lower:
            warnings.append("缺少形变约束(no distorted features)")
        if "do not invent" not in prompt_lower and "not in the source" not in prompt_lower:
            warnings.append("缺少幻觉抑制(do not invent details)")

        # --- Hallucination check (against source content) ---
        # IMPORTANT: Skip [CONSTRAINTS] and [FALLBACK] sections where we TELL
        # the model to avoid these words — those are correct usage, not hallucination.
        prompt_main = prompt.split("[CONSTRAINTS]")[0] if "[CONSTRAINTS]" in prompt else prompt
        source_text = " ".join(source_key_points or []).lower()
        for trigger in cls._HALLUCINATION_TRIGGERS:
            if trigger in prompt_main.lower():
                if trigger not in source_text:
                    issues.append(
                        f"潜在幻觉: 提示词中出现了'{trigger}'但源内容中没有对应信息"
                    )

        # --- Vague content check ---
        for vague in cls._VAGUE_PATTERNS:
            if vague.lower() in prompt.lower():
                warnings.append(f"提示词较模糊: 包含'{vague}'")

        # --- Token efficiency ---
        word_count = len(prompt.split())
        if word_count > 220:
            warnings.append(f"提示词过长 ({word_count}词), 建议压缩至 150-180 词")
        elif word_count < 40:
            issues.append(f"提示词过短 ({word_count}词), 缺乏细节")

        # --- Chinese AI marker check (from antigravity-awesome-skills humanize-chinese) ---
        for marker in cls._CHINESE_AI_MARKERS:
            if marker in prompt:
                warnings.append(f"提示词包含中文AI痕迹: '{marker}'")

        # --- Critical Rules: one main motion only ---
        prompt_lower_local = prompt.lower()
        motion_count = sum(1 for m in [" push-in", " pull-out", " pan ", " orbit", " handheld", " tilt", " crane"]
                          if m in prompt_lower_local)
        if motion_count > 2:
            warnings.append(f"运镜指令过多 ({motion_count}种), 建议只保留1-2种主运镜 (Critical Rules)")

        # --- Critical Rules: no contradictory camera instructions ---
        contradictions = [
            ("push-in", "pull-out"),
            (" handheld", "locked-off"),
            (" handheld", "stable"),
            (" orbit", "locked-off"),
        ]
        for a, b in contradictions:
            if a in prompt_lower_local and b in prompt_lower_local:
                warnings.append(f"矛盾运镜指令: '{a}' 和 '{b}' 不能同时出现 (Critical Rules)")

        # --- Critical Rules: no conflict of shot size ---
        if "close-up" in prompt_lower_local and "wide shot" in prompt_lower_local:
            warnings.append("景别矛盾: close-up 和 wide shot 不应同时出现")

        # --- Score ---
        score = 1.0
        score -= len(issues) * 0.25
        score -= len(warnings) * 0.08
        score = max(0.0, min(1.0, score))

        report.score = round(score, 2)
        report.issues = issues
        report.warnings = warnings
        report.passed = score >= 0.7 and len(issues) == 0  # raised from 0.6 → 0.7
        return report


    @classmethod
    def validate_video_prompt(
        cls,
        prompt: str,
        source_key_points: list[str] | None = None,
    ) -> "PromptValidator.ValidationReport":
        """Validate a video generation prompt (matches new [SCENE]...[FALLBACK] format)."""
        report = cls.ValidationReport(
            prompt_preview=prompt[:120] + ("..." if len(prompt) > 120 else ""),
        )
        issues: list[str] = []
        warnings: list[str] = []

        # --- Structural checks ---
        if "[SCENE]" not in prompt:
            issues.append("缺少 [SCENE] 段落(场景描述)")
        if "[STYLE]" not in prompt:
            warnings.append("缺少 [STYLE] 段落(风格规范)")
        if "[MOTION]" not in prompt:
            issues.append("缺少 [MOTION] 段落(运镜描述)")
        if "[CONSTRAINTS]" not in prompt:
            issues.append("缺少 [CONSTRAINTS] 段落(约束条件)")
        if "[FALLBACK]" not in prompt:
            warnings.append("缺少 [FALLBACK] 段落(兜底策略)")

        # --- Content constraints ---
        prompt_lower = prompt.lower()
        if "no text" not in prompt_lower and "no watermark" not in prompt_lower:
            issues.append("缺少文字/水印约束")
        if "no blank" not in prompt_lower and "no flicker" not in prompt_lower:
            warnings.append("缺少防止空帧/闪烁约束")

        # --- Hallucination check ---
        prompt_main = prompt.split("[CONSTRAINTS]")[0] if "[CONSTRAINTS]" in prompt else prompt
        source_text = " ".join(source_key_points or []).lower()
        for trigger in cls._HALLUCINATION_TRIGGERS:
            if trigger in prompt_main.lower():
                if trigger not in source_text:
                    issues.append(
                        f"潜在幻觉: 提示词中出现了'{trigger}'但源内容中没有对应信息"
                    )

        # --- Motion specificity ---
        if "push-in" not in prompt_lower and "pull-out" not in prompt_lower \
           and "pan" not in prompt_lower and "handheld" not in prompt_lower \
           and "stable" not in prompt_lower and "lock-off" not in prompt_lower:
            warnings.append("没有明确指定运动方式, 视频可能静止或抖动")

        # --- Chinese AI marker check ---
        for marker in cls._CHINESE_AI_MARKERS:
            if marker in prompt:
                warnings.append(f"提示词包含中文AI痕迹: '{marker}'")

        # --- Critical Rules: one main motion only ---
        motion_count = sum(1 for m in [" push-in", " pull-out", " pan ", " orbit", " handheld", " tilt", " crane"]
                          if m in prompt_lower)
        if motion_count > 2:
            warnings.append(f"运镜指令过多 ({motion_count}种), 建议只保留1-2种主运镜 (Critical Rules)")

        # --- Critical Rules: no contradictory camera instructions ---
        contradictions = [
            ("push-in", "pull-out"),
            (" handheld", "locked-off"),
            (" handheld", "stable"),
            (" orbit", "locked-off"),
        ]
        for a, b in contradictions:
            if a in prompt_lower and b in prompt_lower:
                warnings.append(f"矛盾运镜指令: '{a}' 和 '{b}' 不能同时出现 (Critical Rules)")

        # --- Critical Rules: no close-up + wide shot conflict ---
        if "close-up" in prompt_lower and "wide shot" in prompt_lower:
            warnings.append("景别矛盾: close-up 和 wide shot 不应同时出现")

        # --- Score ---
        score = 1.0
        score -= len(issues) * 0.25
        score -= len(warnings) * 0.08
        score = max(0.0, min(1.0, score))

        report.score = round(score, 2)
        report.issues = issues
        report.warnings = warnings
        report.passed = score >= 0.7 and len(issues) == 0  # raised from 0.6 → 0.7
        return report

    @classmethod
    def validate_all(cls, plans: list) -> dict:
        """Validate all prompts across all scene plans.

        Returns a summary dict with pass/fail stats.
        """
        total = len(plans)
        img_passed = 0
        vid_passed = 0
        all_reports: list[dict] = []

        for plan in plans:
            img_report = cls.validate_image_prompt(
                plan.image_prompt,
                getattr(plan, 'characters_in_scene', None),
            )
            vid_report = cls.validate_video_prompt(
                plan.video_prompt,
                getattr(plan, 'characters_in_scene', None),
            )
            if img_report.passed:
                img_passed += 1
            if vid_report.passed:
                vid_passed += 1
            all_reports.append({
                "slide": plan.slide_index,
                "image": {"score": img_report.score, "passed": img_report.passed,
                          "issues": img_report.issues, "warnings": img_report.warnings},
                "video": {"score": vid_report.score, "passed": vid_report.passed,
                          "issues": vid_report.issues, "warnings": vid_report.warnings},
            })

        return {
            "total_slides": total,
            "image_pass_rate": f"{img_passed}/{total}",
            "video_pass_rate": f"{vid_passed}/{total}",
            "reports": all_reports,
        }


