@dataclass
class CharacterRef:
    """A character, product, or key object appearing across slides."""

    name: str
    visual_description: str  # Full visual description for prompts
    role: str  # "protagonist", "product", "supporting", "background"
    reference_images: list[str] = field(default_factory=list)
    slides_appears_in: list[int] = field(default_factory=list)


@dataclass
class SceneSetting:
    """A consistent scene/environment used across multiple slides."""

    name: str
    description: str
    lighting: str = ""
    ambiance: str = ""
    slides_used_in: list[int] = field(default_factory=list)


@dataclass
class ConsistencyGuide:
    """
    Global "Style Bible" — shared visual identity for the entire presentation.

    Every prompt generated by the Director references this guide so that
    characters, products, environments, lighting, colours, and mood stay
    consistent from the first frame to the last.
    """

    aesthetic: str
    color_palette: str
    lighting_scheme: str
    camera_signature: str  # e.g. "prime lenses, shallow depth of field"
    mood: str
    characters: list[CharacterRef] = field(default_factory=list)
    settings: list[SceneSetting] = field(default_factory=list)
    core_props: list[str] = field(default_factory=list)
    era_or_theme: str = ""  # e.g. "futuristic 2087" or "classic 1950s diner"
    overall_theme: str = ""

    def to_prompt_prefix(self) -> str:
        """Return a structured style anchor block repeated in every image/video prompt.

        This is the "global style bible" — ensures every generated frame
        looks like it belongs to the same production.
        """
        parts = [
            f"[GLOBAL STYLE ANCHOR — APPLY TO ALL SCENES]",
            f"Visual Style: {self.aesthetic}.",
            f"Lighting: {self.lighting_scheme}.",
            f"Color Palette: {self.color_palette}.",
            f"Mood: {self.mood}.",
            f"Camera Signature: {self.camera_signature}.",
            f"Era/Setting: {self.era_or_theme or 'modern'}.",
        ]
        if self.core_props:
            parts.append(f"Consistent Props: {', '.join(self.core_props)}.")
        if self.characters:
            chars_desc = "; ".join(
                f"{c.name} ({c.role}): {c.visual_description}"
                for c in self.characters
            )
            parts.append(f"Character/Product Registry: {chars_desc}.")
        if self.settings:
            settings_desc = "; ".join(
                f"{s.name}: {s.description}"
                for s in self.settings
            )
            parts.append(f"Setting Registry: {settings_desc}.")
        parts.append("[END GLOBAL STYLE ANCHOR]")
        return " ".join(parts)

    def character_names(self) -> list[str]:
        return [c.name for c in self.characters]

    def get_character(self, name: str) -> Optional[CharacterRef]:
        for c in self.characters:
            if c.name.lower() == name.lower():
                return c
        return None


