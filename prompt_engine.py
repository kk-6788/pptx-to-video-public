    def _extract_characters(self, slides: list[Slide]) -> list[CharacterRef]:
        """
        Extract characters/products that appear repeatedly across slides.
        Uses keyword heuristics + frequency analysis.
        """
        # Collect all unique significant words across slides
        word_freq: dict[str, int] = {}
        slide_words: dict[str, list[int]] = {}

        for s in slides:
            text = (s.title or "") + " " + (s.text_content or "")
            # Extract capitalized multi-word phrases (likely proper nouns / product names)
            phrases = re.findall(r'[A-Z][a-z]+(?:\s+[A-Z][a-z]+)*', text)
            for phrase in phrases:
                phrase_clean = phrase.strip()
                if len(phrase_clean) < 3:
                    continue
                word_freq[phrase_clean] = word_freq.get(phrase_clean, 0) + 1
                if phrase_clean not in slide_words:
                    slide_words[phrase_clean] = []
                slide_words[phrase_clean].append(s.index)

            # Also look for "product", "solution", "system" references
            single_words = re.findall(r'\b([A-Z][a-z]{2,})\b', text)
            for w in single_words:
                if w not in ("The", "This", "Our", "With", "From", "What", "How", "Why"):
                    word_freq[w] = word_freq.get(w, 0) + 1
                    if w not in slide_words:
                        slide_words[w] = []
                    slide_words[w].append(s.index)

        # Build characters from frequently occurring terms
        characters: list[CharacterRef] = []
        # Products / named entities that appear in 2+ slides
        for phrase, freq in sorted(word_freq.items(), key=lambda x: -x[1]):
            if freq >= 2 and len(phrase) >= 4:
                slides_for = sorted(set(slide_words[phrase]))
                if phrase not in [c.name for c in characters]:
                    characters.append(CharacterRef(
                        name=phrase,
                        visual_description=self._describe_entity(phrase),
                        role="product" if any(kw in phrase.lower() for kw in
                                              ("product", "solution", "system", "device", "model")) else "protagonist",
                        slides_appears_in=slides_for,
                    ))

        # If no multi-slide entities found, extract the first key subject
        if not characters:
            for s in slides:
                subject = (s.title or s.text_content or "").strip()
                if subject:
                    first_word = subject.split()[0] if subject.split() else ""
                    if first_word and len(first_word) > 2:
                        characters.append(CharacterRef(
                            name=first_word,
                            visual_description=f"Main subject of the presentation, professional appearance",
                            role="protagonist",
                            slides_appears_in=[s.index],
                        ))
                    break

        return characters

    def _describe_entity(self, name: str) -> str:
        """Generate a visual description for a named entity."""
        name_lower = name.lower()
        if any(kw in name_lower for kw in ("phone", "device", "gadget", "product")):
            return f"Sleek modern {name} with premium metallic finish, smooth surfaces, elegant design"
        if any(kw in name_lower for kw in ("software", "platform", "solution", "system")):
            return f"Digital interface of {name} displayed on a high-end screen, clean modern UI"
        if any(kw in name_lower for kw in ("person", "founder", "ceo", "user", "customer")):
            return f"Professional {name} in modern business attire, confident posture"
        return f"{name} — high-end professional subject, photorealistic"

    def _extract_settings(self, slides: list[Slide]) -> list[SceneSetting]:
        """Detect recurring scenes/environments."""
        settings: list[SceneSetting] = []
        all_text = " ".join(s.text_content for s in slides).lower()

        # Simple environment detection
        env_keywords = {
            "office": "Modern professional office with clean lines, glass walls, plants",
            "studio": "Professional photography studio with seamless backdrop, soft lighting",
            "outdoor": "Outdoor urban setting with clean architecture, natural light",
            "lab": "High-tech laboratory environment with holographic displays, clean surfaces",
            "home": "Modern comfortable home setting with warm decor, natural materials",
            "factory": "Advanced manufacturing facility with clean automated production lines",
            "nature": "Natural landscape with organic forms, soft greenery, open sky",
        }

        for keyword, desc in env_keywords.items():
            if keyword in all_text:
                slide_indices = []
                for s in slides:
                    if keyword in (s.text_content or "").lower():
                        slide_indices.append(s.index)
                if slide_indices:
                    settings.append(SceneSetting(
                        name=f"{keyword.title()} Environment",
                        description=desc,
                        lighting="ambient environment lighting matching the setting" if keyword != "studio" else "controlled studio lighting",
                        ambiance="professional and clean" if keyword in ("office", "lab", "studio") else "natural and organic",
                        slides_used_in=slide_indices,
                    ))

        # Default setting if none detected
        if not settings:
            style_name = self._raw_style.get("aesthetic", "professional").lower()
            settings.append(SceneSetting(
                name="Presentation Setting",
                description=f"Clean {style_name} setting with professional backdrop",
                lighting=self._raw_style.get("lighting", "Soft studio lighting"),
                ambiance=self._raw_style.get("mood", "Professional"),
                slides_used_in=[s.index for s in slides],
            ))

        return settings

    def _extract_core_props(self, slides: list[Slide]) -> list[str]:
        """Extract recurring props / visual elements."""
        all_text = " ".join(s.text_content for s in slides).lower()
        props = []

        prop_keywords = [
            "screen", "display", "dashboard", "chart", "graph",
            "device", "smartphone", "tablet", "laptop",
            "document", "report", "blueprint", "prototype",
        ]
        for kw in prop_keywords:
            if kw in all_text:
                props.append(kw)

        return props

