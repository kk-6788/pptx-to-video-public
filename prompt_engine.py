class ScriptWriter:
    """
    Analyzes ALL slides holistically to generate a narrative script.

    Instead of treating each slide as one scene, ScriptWriter:

    1. **Groups slides into logical acts/chapters** based on topic similarity,
       title hierarchy, and content transitions.
    2. **Generates narrative scenes** that may span multiple slides or merge
       related content into cohesive visual moments.
    3. **Produces a Script** that the Director can then use to generate prompts.

    The result is a more natural video that feels like a coherent story
    rather than a linear slide-by-slide recording.
    """

    # Language-specific strings
    _LANG = {
        "zh-CN": {
            "title": "PPT 视频剧本",
            "act": "第{num}幕",
            "opening": "开场",
            "closing": "总结收尾",
            "transition": "转场衔接",
            "intro_scene": "开场介绍",
            "summary_scene": "总结与展望",
        },
        "en": {
            "title": "PPT Video Script",
            "act": "Act {num}",
            "opening": "Opening",
            "closing": "Closing",
            "transition": "Transition",
            "intro_scene": "Introduction",
            "summary_scene": "Summary & Outlook",
        },
    }

    def __init__(
        self,
        slides: list[Slide],
        language: str = "zh-CN",
        overall_theme: str = "",
        use_case: str = "auto",
        total_duration: float = 0.0,
        narration_style: str = "direct",
    ) -> None:
        """
        Args:
            slides: Parsed slides.
            language: 'zh-CN' or 'en'.
            overall_theme: Optional theme override.
            use_case: Narrative structure key (auto, education, ecommerce, ...).
            total_duration: Target total video duration in seconds.
                0.0 = auto-calculate from slide count.
        """
        self._slides = slides
        self._lang_code = language if language in self._LANG else "zh-CN"
        self._overall_theme = overall_theme
        self._use_case = use_case if use_case in _USE_CASE_STRUCTURES else "auto"
        self._total_duration = float(total_duration) if total_duration > 0 else 0.0
        self._str = self._LANG[self._lang_code]
        if narration_style not in {"direct", "explain"}:
            raise ValueError("narration_style must be 'direct' or 'explain'")
        self._narration_style = narration_style

    def write(self) -> Script:
        """
        Analyze slides holistically and produce a Script.
        ...
        """
        slides = self._slides
        if not slides:
            return Script(title="", scenes=[], overall_theme=self._overall_theme, language=self._lang_code)

        # 0. Get use-case structure if specified
        use_case_data = _USE_CASE_STRUCTURES.get(self._use_case, {})

        # 1. Group slides into logical chapters
        if use_case_data and use_case_data.get("structure"):
            groups = self._group_by_use_case(slides, use_case_data)
        else:
            groups = self._group_slides(slides)

        # 2. Build scene for each group
        scenes: list[ScriptScene] = []
        total_slides_in_groups = sum(len(g) for g, _ in groups)
        for gi, (group_slides, act_name) in enumerate(groups):
            scene = self._build_scene(group_slides, gi, act_name, len(groups), total_slides_in_groups)
            scenes.append(scene)

        # 3. Post-process: add narrative bridges
        self._add_transitions(scenes)

        # 4. Build title
        title = self._extract_title(slides)
        if not title:
            title = self._str["title"]

        return Script(
            title=title,
            scenes=scenes,
            overall_theme=self._overall_theme,
            language=self._lang_code,
        )

    def _group_slides(
        self, slides: list[Slide]
    ) -> list[tuple[list[Slide], str]]:
        """
        Group slides into logical chapters/acts.

        Strategy:
        - First slide is "opening"
        - Last slide is "closing"
        - Remaining slides are grouped by content similarity
          with a minimum group size of ~3 slides.
        """
        groups: list[tuple[list[Slide], str]] = []
        n = len(slides)

        if n == 0:
            return groups

        # Opening (slide 0)
        groups.append(([slides[0]], self._str["opening"]))

        if n > 2:
            # Middle slides — group by content similarity
            middle = slides[1:-1]
            sub_groups = self._cluster_slides(middle)
            for sg in sub_groups:
                groups.append((sg, self._str["act"].format(num=len(groups))))

        # Closing (last slide, if more than 1)
        if n > 1:
            groups.append(([slides[-1]], self._str["closing"]))

        return groups

    def _is_topic_transition(self, prev: Slide, curr: Slide) -> bool:
        """Detect a MAJOR topic change between slides.

        Only returns True when content is genuinely unrelated,
        not just when titles differ (which is normal within a topic).
        """
        prev_text = ((prev.title or "") + " " + (prev.text_content or "")).lower()
        curr_text = ((curr.title or "") + " " + (curr.text_content or "")).lower()

        # Remove very common stopwords for meaningful comparison
        common = {"the", "a", "an", "is", "are", "was", "were", "be", "been",
                  "has", "have", "had", "do", "does", "did", "will", "would",
                  "can", "could", "may", "might", "shall", "should", "to", "of",
                  "in", "for", "on", "with", "at", "by", "from", "as", "into",
                  "this", "that", "these", "those", "it", "its", "our", "your",
                  "and", "or", "but", "not", "no", "if", "about", "up", "out",
                  "的", "了", "是", "在", "和", "也", "就", "都", "而", "及",
                  "与", "着", "或", "一个", "没有", "我们", "你们", "他们",
                  "可以", "这个", "那个", "不", "会", "有", "要", "以", "对"}
        prev_words = set(w for w in prev_text.split() if w not in common and len(w) > 1)
        curr_words = set(w for w in curr_text.split() if w not in common and len(w) > 1)

        if not prev_words or not curr_words:
            return False  # No meaningful words → assume same topic

        overlap = len(prev_words & curr_words)
        total = len(prev_words | curr_words)
        # Only flag transition when overlap is VERY low (< 8%)
        return overlap / total < 0.08

    def _cluster_slides(self, slides: list[Slide]) -> list[list[Slide]]:
        """Cluster middle slides into larger groups by content similarity.

        Guarantees at most ceil(N/3) groups for N middle slides.
        """
        if len(slides) <= 1:
            return [slides]

        n = len(slides)
        # Target: at most n // 3 groups, minimum 3 slides per group
        target_groups = max(1, n // 3)
        base_size = max(3, n // target_groups) if target_groups > 0 else n

        clusters: list[list[Slide]] = []
        current: list[Slide] = []

        for slide in slides:
            current.append(slide)
            if len(current) >= base_size:
                clusters.append(current)
                current = []

        if current:
            if clusters:
                clusters[-1].extend(current)
            else:
                clusters.append(current)

        # Post-merge: combine groups with similar topics
        merged: list[list[Slide]] = [clusters[0]] if clusters else []
        for i in range(1, len(clusters)):
            prev_group = merged[-1]
            curr_group = clusters[i]
            is_transition = self._is_topic_transition(prev_group[-1], curr_group[0])
            # Merge unless: clear transition AND both groups ≥ 3
            should_merge = not (is_transition and len(prev_group) >= 3 and len(curr_group) >= 3)
            if should_merge:
                prev_group.extend(curr_group)
            else:
                merged.append(curr_group)

        return merged

    def _group_by_use_case(
        self, slides: list[Slide], use_case_data: dict
    ) -> list[tuple[list[Slide], str]]:
        """
        Group slides according to the use-case narrative structure.

        Distributes slides across the predefined structure steps,
        with the first slide as opening, last as closing.
        """
        structure = use_case_data.get("structure", [])
        labels = use_case_data.get("scene_labels", structure)
        groups: list[tuple[list[Slide], str]] = []
        n = len(slides)

        if n == 0:
            return groups

        # Opening = first slide
        groups.append(([slides[0]], structure[0] if structure else "开场"))

        if n > 2 and len(structure) > 2:
            # Distribute middle slides across the structure's middle steps
            middle_slides = slides[1:-1]
            middle_steps = structure[1:-1]
            steps_count = len(middle_steps)
            if steps_count > 0:
                # Distribute slides across steps
                per_step = max(1, len(middle_slides) // steps_count)
                for si, step_name in enumerate(middle_steps):
                    start = si * per_step
                    end = start + per_step if si < steps_count - 1 else len(middle_slides)
                    chunk = middle_slides[start:end]
                    groups.append((chunk, step_name))
            else:
                groups.append((middle_slides, "内容"))

        # Closing = last slide
        if n > 1:
            groups.append(([slides[-1]], structure[-1] if len(structure) > 1 else "收尾"))

        return groups

    def _build_scene(
        self,
        group_slides: list[Slide],
        group_idx: int,
        act_name: str,
        total_groups: int,
        total_slides_in_groups: int = 0,
    ) -> ScriptScene:
        """Generate a narrative scene from a group of slides."""
        indices = [s.index for s in group_slides]
        all_text = " ".join(s.text_content or "" for s in group_slides)
        titles = [s.title for s in group_slides if s.title]

        # Scene title
        if titles:
            scene_title = " | ".join(titles[:2])
            if len(titles) > 2:
                scene_title += " …"
        else:
            scene_title = f"第{group_idx+1}部分"

        # Scene description (use-case aware)
        uc_data = _USE_CASE_STRUCTURES.get(self._use_case, {})
        templates = uc_data.get("description_templates", {})
        if self._use_case != "auto" and templates:
            if group_idx == 0:
                desc = templates.get("opening", self._describe_opening(group_slides))
            elif group_idx == total_groups - 1:
                desc = templates.get("closing", self._describe_closing(group_slides))
            else:
                desc = templates.get("middle", self._describe_middle(group_slides))
        else:
            if group_idx == 0:
                desc = self._describe_opening(group_slides)
            elif group_idx == total_groups - 1:
                desc = self._describe_closing(group_slides)
            else:
                desc = self._describe_middle(group_slides)

        # Director's vision (cinematic interpretation)
        vision = self._write_director_vision(group_slides, group_idx, total_groups)

        # Key points
        key_points = []
        for s in group_slides:
            text = s.text_content or ""
            for line in text.split("\n"):
                line = line.strip().strip("- ").strip()
                if line and len(line) > 10 and line not in key_points:
                    key_points.append(line)

        # Duration (more slides = longer scene)
        if self._total_duration > 0 and total_slides_in_groups > 0:
            # Distribute total_duration proportionally by slide count
            ratio = len(group_slides) / total_slides_in_groups
            duration = self._total_duration * ratio
        else:
            # Legacy heuristic: ~3.2s per slide, clamped to 4-15s
            duration = 3.2 * len(group_slides)
        duration = max(3.0, min(duration, 30.0))

        narration_by_slide = {
            slide.index: build_slide_narration(slide, self._narration_style)
            for slide in group_slides
        }
        return ScriptScene(
            scene_number=group_idx + 1,
            act_name=act_name,
            title=scene_title,
            description=desc,
            director_vision=vision,
            slide_indices=indices,
            key_points=key_points[:5],
            suggested_duration_sec=round(duration, 1),
            narration_style=self._narration_style,
            narration_text="".join(narration_by_slide.values()),
            narration_by_slide=narration_by_slide,
        )

    def _describe_opening(self, slides: list[Slide]) -> str:
        """Generate opening scene description — content-aware, not just template."""
        t = self._str
        if self._lang_code == "zh-CN":
            title = slides[0].title or "主题"
            # Extract first concrete bullet point for specificity
            concrete = ""
            text = slides[0].text_content or ""
            for line in text.split("\n"):
                line = line.strip().strip("- \u2022·").strip()
                if line and len(line) > 10:
                    concrete = f" 内容线索：{line[:80]}。"
                    break
            return (
                f"开场场景。介绍主题「{title}」，设定整体基调和视觉风格，吸引观众注意力。"
                f"{concrete}"
            )
        else:
            title = slides[0].title or "the topic"
            return f"Opening scene. Introducing '{title}', setting the overall tone and visual style, capturing the audience's attention."

    def _describe_closing(self, slides: list[Slide]) -> str:
        """Generate closing scene description — content-aware, not just template."""
        t = self._str
        if self._lang_code == "zh-CN":
            title = slides[0].title or "总结"
            # Extract conclusion keywords
            concrete = ""
            text = slides[0].text_content or ""
            for line in text.split("\n"):
                line = line.strip().strip("- \u2022·").strip()
                if line and len(line) > 10:
                    concrete = f" 关键收束：{line[:80]}。"
                    break
            return (
                f"收尾场景。总结核心观点，「{title}」，留下深刻印象，呼吁行动或展望未来。"
                f"{concrete}"
            )
        else:
            title = slides[0].title or "summary"
            return f"Closing scene. Summarizing key takeaways, '{title}', leaving a lasting impression with a call to action or future outlook."

    def _describe_middle(self, slides: list[Slide]) -> str:
        """Generate middle scene description — content-aware, not just template."""
        if self._lang_code == "zh-CN":
            titles = [s.title for s in slides if s.title]
            # Collect actual content snippets for specificity
            snippets = []
            for s in slides[:3]:
                text = s.text_content or ""
                for line in text.split("\n"):
                    line = line.strip().strip("- \u2022·").strip()
                    if line and len(line) > 15 and line not in snippets:
                        snippets.append(line[:60])
                        break
            snip_text = ""
            if snippets:
                snip_text = " 核心内容：" + " | ".join(snippets[:3]) + "。"

            if titles:
                topics = "、".join(titles[:3])
                return (
                    f"深度阐述。详细讲解「{topics}」，结合数据、案例和视觉元素展开论证。"
                    f"{snip_text}"
                )
            return f"内容深度展示。通过相关的视觉元素和信息呈现核心论点。{snip_text}"
        else:
            titles = [s.title for s in slides if s.title]
            if titles:
                topics = ", ".join(titles[:3])
                return f"In-depth exploration of '{topics}', combining data, cases, and visual elements."
            return "Deep-dive content presentation with supporting visual elements."

    def _write_director_vision(
        self, group_slides: list[Slide], idx: int, total: int
    ) -> str:
        """Write the director's cinematic vision — Chain-of-Thought approach.

        Reasoning chain (prompt-engineer CoT):
          1. Scene position in narrative (opening/middle/closing)
          2. Scene purpose (introduce/explain/transition/conclude)
          3. Emotional intent (excitement/trust/urgency/reflection)
          4. Visual execution (camera movement, pacing, composition)
          5. Tie to actual slide content (avoid generic descriptions)
        """
        # --- CoT Step 1-2: Position + Purpose ---
        if idx == 0:
            position = "opening"
            purpose = "capture attention, establish theme, set expectations"
            emotion = "anticipation and curiosity"
        elif idx == total - 1:
            position = "closing"
            purpose = "reinforce key message, create lasting impression, call to action"
            emotion = "satisfaction and motivation"
        else:
            position = "middle"
            purpose = "develop narrative, present evidence, build argument"
            emotion = "engagement and trust"

        # --- CoT Step 3-4: Content-aware visual execution ---
        # Extract actual content keywords to make vision specific
        content_words = []
        for s in group_slides[:2]:
            text = (s.title or "") + " " + (s.text_content or "")
            # Take first substantive sentence
            sentences = text.replace("。", ".").split(".")
            for sent in sentences:
                sent = sent.strip()
                if len(sent) > 5:
                    content_words.append(sent[:60])
                    break

        content_hint = ""
        if content_words:
            content_hint = f" Content cue: \"{content_words[0]}\"."

        # --- Build vision string ---
        if self._lang_code == "zh-CN":
            if position == "opening":
                vision = (
                    f"【开场导演视角】{purpose}。情绪基调：{emotion}。"
                    f"运镜：缓缓推入画面，以视觉冲击力确立主题基调。"
                    f"节奏：沉稳有力，给观众消化开场信息的时间。{content_hint}"
                )
            elif position == "closing":
                vision = (
                    f"【收尾导演视角】{purpose}。情绪基调：{emotion}。"
                    f"运镜：镜头缓缓拉远或平稳停留，画面逐渐柔和。"
                    f"节奏：从容收束，让观众回味整部内容。{content_hint}"
                )
            else:
                vision = (
                    f"【展开导演视角】{purpose}。情绪基调：{emotion}。"
                    f"运镜：流畅的视觉叙事，配合内容节奏切换视角。"
                    f"节奏：信息密度适中，保持观众注意力。{content_hint}"
                )
        else:
            if position == "opening":
                vision = (
                    f"[Opening Director's Vision] Purpose: {purpose}. "
                    f"Emotion: {emotion}. "
                    f"Camera: slow push-in, establishing with visual impact. "
                    f"Pacing: deliberate, allowing the audience to absorb opening information."
                    f"{content_hint}"
                )
            elif position == "closing":
                vision = (
                    f"[Closing Director's Vision] Purpose: {purpose}. "
                    f"Emotion: {emotion}. "
                    f"Camera: gentle pull-out or steady hold, scene softens gradually. "
                    f"Pacing: relaxed closure, letting the message resonate."
                    f"{content_hint}"
                )
            else:
                vision = (
                    f"[Narrative Director's Vision] Purpose: {purpose}. "
                    f"Emotion: {emotion}. "
                    f"Camera: smooth visual storytelling, perspective shifts with content rhythm. "
                    f"Pacing: balanced information density, maintaining engagement."
                    f"{content_hint}"
                )

        return vision

    def _add_transitions(self, scenes: list[ScriptScene]) -> None:
        """Add transition descriptions between consecutive scenes."""
        transitions = ["dissolve", "push-in", "match cut", "wipe", "cross-dissolve", "swirl"]
        for i in range(1, len(scenes)):
            tr = transitions[(i - 1) % len(transitions)]
            scenes[i].transition_from_prev = tr

    def _extract_title(self, slides: list[Slide]) -> str:
        """Extract presentation title from first slide or content."""
        if slides and slides[0].title:
            return slides[0].title.strip()
        if slides and slides[0].text_content:
            first_line = slides[0].text_content.strip().split("\n")[0]
            return first_line[:60]
        return ""


