class Director:
    """
    Cinematic director that transforms slides into cohesive, multi-angle
    scene plans with full consistency across the entire presentation.

    The Director:
    1. Builds a **ConsistencyGuide** (Style Bible) from ALL slides.
    2. Generates **multiple keyframe image prompts** per slide (wide, medium,
       close-up, detail — configurable via ``images_per_slide``).
    3. Plans **narrative transitions** between slides.
    4. Suggests **per-slide duration** based on content complexity.
    """

    def __init__(
        self,
        slides: list[Slide],
        style: str | dict[str, str] = "auto",
        overall_theme: str = "",
        images_per_slide: int = 2,
        script: Script | None = None,
        narration_style: str = "direct",
        visual_mode: str = "creative",
    ) -> None:
        self._slides = slides
        self._overall_theme = overall_theme
        self._images_per_slide = max(1, min(images_per_slide, 8))  # clamp 1-8
        self._script = script
        self._language = script.language if script else "zh-CN"
        if narration_style not in {"direct", "explain"}:
            raise ValueError("narration_style must be 'direct' or 'explain'")
        self._narration_style = narration_style
        if visual_mode not in {"faithful", "creative"}:
            raise ValueError("visual_mode must be faithful or creative")
        self._visual_mode = visual_mode

        # Build the ConsistencyGuide first
        engine = ConsistencyEngine(slides, style=style, overall_theme=overall_theme)
        self._guide: ConsistencyGuide = engine.build()
        self._raw_style = engine._raw_style

        logger.info(
            "Director initialized: %d slides, %d images/slide, %d characters, %d settings",
            len(slides), self._images_per_slide,
            len(self._guide.characters), len(self._guide.settings),
        )

    @property
    def guide(self) -> ConsistencyGuide:
        """The Style Bible built for this presentation."""
        return self._guide

    @property
    def style_description(self) -> str:
        if self._visual_mode == "faithful":
            return "忠实讲解：使用 PPT 原文与原图，按原页顺序渐进呈现"
        s = self._raw_style
        return (
            f"Aesthetic: {s.get('aesthetic', '')}\n"
            f"Lighting:  {s.get('lighting', '')}\n"
            f"Mood:      {s.get('mood', '')}\n"
            f"Camera:    {s.get('camera', '')}\n"
            f"Colour:    {s.get('colour', '')}"
        )

    def plan(self) -> list[EnhancedScenePlan]:
        """Generate enhanced scene plans.

        If a Script was provided (from ScriptWriter), plan per script scene.
        Otherwise, fall back to the original per-slide approach.
        """
        if self._visual_mode == "faithful":
            from faithful_plan import build_faithful_plans
            return build_faithful_plans(self._slides, self._narration_style)
        if self._script is not None and self._script.scenes:
            return self._plan_from_script(self._script)

        guide = self._guide
        consistency_prefix = guide.to_prompt_prefix()

        plans: list[EnhancedScenePlan] = []

        for i, slide in enumerate(self._slides):
            plan = self._plan_slide(
                slide=slide,
                idx=i,
                total=len(self._slides),
                guide=guide,
                consistency_prefix=consistency_prefix,
            )
            plans.append(plan)

        # Post-processing: add narrative bridges between consecutive slides
        self._add_narrative_bridges(plans)

        logger.info("Director produced %d enhanced scene plans (per-slide)", len(plans))
        return plans

    def _plan_from_script(self, script: Script) -> list[EnhancedScenePlan]:
        """Generate scene plans from a Script (holistic understanding)."""
        guide = self._guide
        consistency_prefix = guide.to_prompt_prefix()
        plans: list[EnhancedScenePlan] = []
        slides_by_index = {slide.index: slide for slide in self._slides}

        for si, scene in enumerate(script.scenes):
            # Gather all text from slides covered by this scene
            covered_slides = [slides_by_index[i] for i in dict.fromkeys(scene.slide_indices)
                              if i in slides_by_index]
            if not covered_slides:
                logger.warning("Skipping script scene %s: it has no matching source slides", scene.scene_number)
                continue
            combined_text = " ".join(s.text_content or "" for s in covered_slides)
            combined_title = " | ".join(s.title for s in covered_slides if s.title) or scene.title
            subject = combined_title or "Scene subject"

            # Characters in this scene
            chars_in_scene = []
            for s in covered_slides:
                chars_in_scene.extend(self._find_characters_in_slide(s, guide))
            chars_in_scene = list(set(chars_in_scene))

            # Setting
            setting = guide.settings[0] if guide.settings else None
            for s in covered_slides:
                st = self._find_setting_for_slide(s, guide)
                if st:
                    setting = st
                    break

            # Angles
            num_angles = min(self._images_per_slide, len(_CAMERA_ANGLES))
            angle_base = (si * num_angles) % len(_CAMERA_ANGLES)
            angles = [_CAMERA_ANGLES[(angle_base + a) % len(_CAMERA_ANGLES)] for a in range(num_angles)]
            primary_angle = angles[0]

            # Shot type based on scene position
            if si == 0:
                shot_type = "Opening establishing shot"
            elif si == len(script.scenes) - 1:
                shot_type = "Closing / summary shot"
            else:
                shot_type = "Narrative scene development"

            # Duration
            duration = scene.suggested_duration_sec

            # Transition
            transition_type = scene.transition_from_prev
            if re.search(r"fade.*black|black.*fade", transition_type, re.IGNORECASE):
                transition_type = "dissolve"

            # Build director vision from script
            director_vision = (
                f"{scene.director_vision} "
                f"Mood: {guide.mood}. Camera: {primary_angle}. "
                f"Transition: {transition_type}."
            )

            # Key points
            key_points = scene.key_points or []

            # Build image prompts (multi-angle keyframes)
            image_prompts: list[str] = []
            image_angles: list[str] = []
            for ai, angle in enumerate(angles):
                angle_short = angle.split("—")[0].strip()
                img_prompt = self._build_image_prompt(
                    subject=subject,
                    consistency_prefix=consistency_prefix,
                    key_points=key_points,
                    angle_description=angle,
                    characters_in_scene=chars_in_scene,
                    setting=setting,
                    shot_type=shot_type,
                    scene_duration=duration,
                    scene_description=scene.description,
                )
                image_prompts.append(img_prompt)
                image_angles.append(angle_short)

            primary_image_prompt = image_prompts[0]

            # Video prompt
            video_prompt = self._build_video_prompt(
                subject=subject,
                consistency_prefix=consistency_prefix,
                key_points=key_points,
                camera_angle_description=primary_angle,
                shot_type=shot_type,
                characters_in_scene=chars_in_scene,
                setting=setting,
                scene_duration=duration,
                scene_description=scene.description,
            )

            narration_by_slide = {
                slide.index: scene.narration_by_slide.get(slide.index)
                or build_slide_narration(slide, scene.narration_style)
                for slide in covered_slides
            }
            plan = EnhancedScenePlan(
                slide_index=covered_slides[0].index,
                director_vision=director_vision,
                image_prompt=primary_image_prompt,
                video_prompt=video_prompt,
                image_prompts=image_prompts,
                image_angles=image_angles,
                characters_in_scene=chars_in_scene,
                setting_name=setting.name if setting else "",
                camera_angle=primary_angle,
                transition_type=transition_type,
                transition_description=transition_type,
                narrative_bridge=scene.description,
                suggested_duration_sec=duration,
                subtitle_text=self._build_subtitle_text(key_points),
                slide_indices=[slide.index for slide in covered_slides],
                narration_style=scene.narration_style,
                narration_text=scene.narration_text or "".join(narration_by_slide.values()),
                narration_by_slide=narration_by_slide,
            )
            plans.append(plan)

        logger.info("Director produced %d enhanced scene plans (from script)", len(plans))
        return plans

    def _plan_slide(
        self,
        slide: Slide,
        idx: int,
        total: int,
        guide: ConsistencyGuide,
        consistency_prefix: str,
    ) -> EnhancedScenePlan:
        title = slide.title or ""
        body = slide.body or ""
        text = slide.text_content or ""

        # --- Shot type ---
        if idx == 0:
            shot_type = "Opening establishing shot"
        elif idx == total - 1:
            shot_type = "Closing / summary shot"
        elif idx % 3 == 0:
            shot_type = "Detail / focus shot"
        else:
            shot_type = "Transition / support shot"

        # --- Subject ---
        subject = self._extract_subject(title, body, text)

        # --- Characters in this scene ---
        chars_in_scene = self._find_characters_in_slide(slide, guide)

        # --- Setting for this slide ---
        setting = self._find_setting_for_slide(slide, guide)

        # --- Camera angles for this slide ---
        num_angles = min(self._images_per_slide, len(_CAMERA_ANGLES))
        angle_indices = [(idx * num_angles + a) % len(_CAMERA_ANGLES) for a in range(num_angles)]
        angles = [_CAMERA_ANGLES[i] for i in angle_indices]

        # --- Primary camera angle ---
        primary_angle = angles[0]

        # --- Transition ---
        transition_type = "cut" if idx == 0 else _TRANSITIONS[idx % len(_TRANSITIONS)]

        # --- Key points ---
        key_points = self._extract_key_points(body, text)

        # --- Duration suggestion (content-based) ---
        text_len = len(text)
        # Simple heuristic: more text = more time needed
        if text_len > 300:
            duration = 8.0
        elif text_len > 150:
            duration = 6.0
        elif text_len > 50:
            duration = 5.0
        else:
            duration = 4.0
        # Add time for images
        if slide.image_paths:
            duration += 1.0
        # Opening/closing slides get slightly more time
        if idx == 0 or idx == total - 1:
            duration += 1.0

        # ── Build Director's Vision ──
        char_str = ""
        if chars_in_scene:
            char_str = f"Featuring: {', '.join(chars_in_scene)}. "
        setting_str = f"Setting: {setting.name}. " if setting else ""

        director_vision = (
            f"{shot_type} of {subject}. {char_str}{setting_str}"
            f"Mood: {guide.mood}. "
            f"Camera: {primary_angle}. "
            f"Transition: {transition_type}."
        )

        # ── Build MULTIPLE image prompts (keyframes) ──
        image_prompts: list[str] = []
        image_angles: list[str] = []

        for ai, angle in enumerate(angles):
            angle_short = angle.split("—")[0].strip()
            img_prompt = self._build_image_prompt(
                subject=subject,
                consistency_prefix=consistency_prefix,
                key_points=key_points,
                angle_description=angle,
                characters_in_scene=chars_in_scene,
                setting=setting,
                shot_type=shot_type,
                scene_duration=duration,
            )
            image_prompts.append(img_prompt)
            image_angles.append(angle_short)

        # ── Build primary image prompt (first angle) ──
        primary_image_prompt = image_prompts[0]

        # ── Build VIDEO prompt ──
        video_prompt = self._build_video_prompt(
            subject=subject,
            consistency_prefix=consistency_prefix,
            key_points=key_points,
            camera_angle_description=primary_angle,
            shot_type=shot_type,
            characters_in_scene=chars_in_scene,
            setting=setting,
            scene_duration=duration,
        )

        narration_text = build_slide_narration(slide, self._narration_style)
        return EnhancedScenePlan(
            slide_index=slide.index,
            director_vision=director_vision,
            image_prompt=primary_image_prompt,
            video_prompt=video_prompt,
            # Extended fields
            image_prompts=image_prompts,
            image_angles=image_angles,
            characters_in_scene=chars_in_scene,
            setting_name=setting.name if setting else "",
            camera_angle=primary_angle,
            transition_type=transition_type,
            transition_description=transition_type,
            narrative_bridge="",
            suggested_duration_sec=duration,
            subtitle_text=self._build_subtitle_text(key_points),
            slide_indices=[slide.index],
            narration_style=self._narration_style,
            narration_text=narration_text,
            narration_by_slide={slide.index: narration_text},
        )

    def _build_image_prompt(
        self,
        subject: str,
        consistency_prefix: str,
        key_points: list[str],
        angle_description: str,
        characters_in_scene: list[str],
        setting: Optional[SceneSetting],
        shot_type: str,
        scene_duration: float = 5.0,
        scene_description: str = "",
    ) -> str:
        """Build a detailed image prompt — prompt-engineer: Role-Constraint-Output.

        Architecture (prompt-engineer methodology):
          [ROLE]       → Who generates this image (cinematic AI artist)
          [TASK]       → Scene description with actual slide content
          [STYLE REF]  → Global style bible + shot type + lighting
          [COMPOSITE]  → Camera angle, setting, position, framing
          [CONSTRAINTS]→ What NOT to generate (watermark, distortion, hallucination)
          [FALLBACK]   → When uncertain, stay generic (no fabricated specifics)

        Also uses Chain-of-Thought: key_points → narrative intent → visual output.
        """
        # ── Chain-of-Thought: determine visual execution from content ──
        # CoT Step 1: Understand content intent
        if key_points:
            _cn_brief = key_points[0] if key_points else subject
        else:
            _cn_brief = scene_description or subject

        # CoT Step 2: Determine camera distance from content type
        if any(kw in (subject + " " + _cn_brief).lower()
               for kw in ("detail", "close-up", "特写", "细节", "放大", "局部")):
            _cot_distance = "close distance, macro-level detail visible"
        elif any(kw in (subject + " " + _cn_brief).lower()
                 for kw in ("overview", "全景", "总览", "全局", "全部展示")):
            _cot_distance = "wide distance, full scene visible"
        else:
            _cot_distance = "medium distance, balanced framing"

        # CoT Step 3: Determine emphasis from shot_type
        if "opening" in shot_type.lower():
            _cot_emphasis = "dramatic, high-impact composition, establishing mood"
        elif "closing" in shot_type.lower() or "summary" in shot_type.lower():
            _cot_emphasis = "resolved, satisfying composition, gentle closure"
        else:
            _cot_emphasis = "focused, informative composition, clear subject priority"

        # ── Chinese context prefix ──
        _cn_prefix = ""
        if getattr(self, '_language', 'zh-CN') == "zh-CN":
            _cn_prefix = f"[中文场景] {_cn_brief}. " if _cn_brief else ""

        # ── [ROLE] Who is generating this ──
        role_parts = [
            "[ROLE] You are a cinematic AI photographer specializing in product and scene photography.",
            f"Shot type: {shot_type}.",
        ]

        # ── [TASK] What to create ──
        task_parts = [f"[TASK] Generate a high-quality image of: {subject}."]
        if characters_in_scene:
            task_parts.append(f"Characters/Products visible: {', '.join(characters_in_scene)}.")
        if key_points:
            kp_text = " | ".join(key_points[:3])
            task_parts.append(f"Key narrative content to reflect: {kp_text}.")
        elif scene_description:
            task_parts.append(f"Scene intent: {scene_description}.")

        # ── [STYLE] Global style bible reference ──
        style_parts = [
            f"[STYLE] {consistency_prefix}",
            f"Distance: {_cot_distance}. Emphasis: {_cot_emphasis}.",
        ]

        # ── [COMPOSITION] Camera + setting ──
        comp_parts = [f"[COMPOSITION] Frame: {_frame_description()}.",
                      f"Camera angle: {angle_description}."]
        if setting:
            comp_parts.append(f"Setting: {setting.description}.")
        comp_parts.append("Cinematic lighting, rich color grading, consistent color temperature.")

        # ── [CONSTRAINTS] What NOT to do — hallucination suppression ──
        constraints_parts = [
            "[CONSTRAINTS]",
            "NO text, NO watermark, NO logo, NO text overlay on image.",
            "NO distorted features, NO deformed anatomy, NO blurry elements.",
            "NO fabricated pricing, NO promotional text, NO fake labels.",
            "If the source content does not specify a detail (price, date, name), do NOT invent it.",
            "Photorealistic, sharp focus, 8K quality.",
            "Maintain consistent character/product appearance across all scenes.",
            f"Duration ~{scene_duration:.0f}s.",
        ]

        # ── [FALLBACK] When uncertain ──
        fallback_parts = [
            "[FALLBACK] If any aspect of the requested scene is ambiguous,",
            "default to a clean, professional presentation without invented specifics.",
        ]

        return (
            _cn_prefix
            + " ".join(role_parts) + " "
            + " ".join(task_parts) + " "
            + " ".join(style_parts) + " "
            + " ".join(comp_parts) + " "
            + " ".join(constraints_parts) + " "
            + " ".join(fallback_parts)
        )

    def _build_video_prompt(
        self,
        subject: str,
        consistency_prefix: str,
        key_points: list[str],
        camera_angle_description: str,
        shot_type: str,
        characters_in_scene: list[str],
        setting: Optional[SceneSetting],
        scene_duration: float = 5.0,
        scene_description: str = "",
    ) -> str:
        """Build a video prompt — prompt-engineer: Role-Constraint-Output.

        Architecture:
          [SCENE]      → Subject + actual slide content (key_points, not generic)
          [STYLE]      → Global style bible anchor
          [MOTION]     → Camera movement, pacing, transitions between keyframes
          [CONSTRAINTS]→ Artifact prevention + hallucination suppression
          [FALLBACK]   → When uncertain, stay stable (no invented motion or text)

        Chain-of-Thought: scene position → appropriate motion style → visual output.
        """
        # ── Chain-of-Thought: determine motion style from scene position ──
        if "opening" in shot_type.lower():
            _cot_motion = "Slow push-in or dolly forward, revealing the scene deliberately"
        elif "closing" in shot_type.lower() or "summary" in shot_type.lower():
            _cot_motion = "Gentle pull-out or slow drift, creating a sense of resolution"
        elif "detail" in shot_type.lower() or "focus" in shot_type.lower():
            _cot_motion = "Subtle handheld sway, very slow, drawing attention to specific detail"
        elif "transition" in shot_type.lower():
            _cot_motion = "Smooth lateral pan, linking elements naturally"
        else:
            _cot_motion = "Gentle, stable camera, minimal movement, professional lock-off"

        # ── Chinese context prefix ──
        _cn_vid_prefix = ""
        if getattr(self, '_language', 'zh-CN') == "zh-CN":
            brief = key_points[0] if key_points else (scene_description or subject)
            _cn_vid_prefix = f"[中文视频场景] {brief}. 画面干净无文字, 中国审美. " if brief else ""

        # ── [SCENE] What to show ──
        scene_parts = [
            f"[SCENE] Subject: {subject}.",
            f"Frame: {_frame_description()}.",
        ]
        if key_points:
            kp_text = " | ".join(key_points[:3])
            scene_parts.append(f"Content: {kp_text}.")
        elif scene_description:
            scene_parts.append(f"Narrative: {scene_description}.")
        if characters_in_scene:
            scene_parts.append(f"Characters/Products: {', '.join(characters_in_scene)}.")
        if setting:
            scene_parts.append(f"Setting: {setting.description}.")

        # ── [STYLE] Global style anchor ──
        style_parts = [
            f"[STYLE] {consistency_prefix}",
        ]

        # ── [MOTION] Camera movement — CoT-determined ──
        motion_parts = [
            f"[MOTION] Camera: {camera_angle_description}.",
            f"Movement: {_cot_motion}.",
            f"Duration: {scene_duration:.0f}s.",
            "Stable frame, no shake, no flicker.",
        ]

        # ── [CONSTRAINTS] Artifact prevention + hallucination suppression ──
        constraints_parts = [
            "[CONSTRAINTS]",
            "NO garbled text, NO distorted characters, NO random symbols on screen.",
            "NO blank/black frames, NO sudden flickering, NO abrupt cuts.",
            "NO subject deformation — faces, products, and props must remain stable and recognizable.",
            "NO fabricated pricing, NO fake promotional text, NO invented labels.",
            "If a detail is not in the source content, do NOT add it visually.",
            "Smooth, continuous, natural motion — no teleporting or popping.",
            "24fps cinematic, professional quality.",
        ]

        # ── [FALLBACK] ──
        fallback_parts = [
            "[FALLBACK] If the video model cannot render a requested element,",
            "keep the frame stable and clean rather than attempting a poor approximation.",
        ]

        return (
            _cn_vid_prefix
            + " ".join(scene_parts) + " "
            + " ".join(style_parts) + " "
            + " ".join(motion_parts) + " "
            + " ".join(constraints_parts) + " "
            + " ".join(fallback_parts)
        )

    # ── Helpers ────────────────────────────────────────────────────────

    def _find_characters_in_slide(self, slide: Slide, guide: ConsistencyGuide) -> list[str]:
        """Determine which characters/products appear on this slide."""
        text = ((slide.title or "") + " " + (slide.text_content or "")).lower()
        found: list[str] = []
        for char in guide.characters:
            name_lower = char.name.lower()
            # Check if the character name or parts of it appear in the text
            if name_lower in text:
                found.append(char.name)
            else:
                # Try individual words of multi-word names
                words = name_lower.split()
                if len(words) > 1 and any(w in text for w in words):
                    found.append(char.name)
        return found

    def _find_setting_for_slide(self, slide: Slide, guide: ConsistencyGuide) -> Optional[SceneSetting]:
        """Determine which setting this slide belongs to."""
        text = ((slide.title or "") + " " + (slide.text_content or "")).lower()
        for setting in guide.settings:
            if slide.index in setting.slides_used_in:
                return setting
            # Fallback: check keywords
            keyword = setting.name.split()[0].lower()
            if keyword in text:
                return setting
        return guide.settings[0] if guide.settings else None

    def _add_narrative_bridges(self, plans: list[EnhancedScenePlan]) -> None:
        """Add narrative flow descriptions between consecutive slides."""
        for i in range(len(plans) - 1):
            current = plans[i]
            nxt = plans[i + 1]

            # Share characters/setting across bridge
            shared_chars = set(current.characters_in_scene) & set(nxt.characters_in_scene)
            # Build bridge description
            bridge_parts = []
            if shared_chars:
                bridge_parts.append(f"Continuing with {', '.join(shared_chars)}")
            if current.setting_name == nxt.setting_name and current.setting_name:
                bridge_parts.append(f"in the same {current.setting_name} setting")
            else:
                bridge_parts.append(f"transitioning from {current.setting_name or 'previous scene'} to {nxt.setting_name or 'next scene'}")

            current.narrative_bridge = ". ".join(bridge_parts) + "."

    @staticmethod
    def _extract_subject(title: str, body: str, text: str) -> str:
        if title:
            return title
        for src in (body, text):
            first = src.split("\n")[0] if "\n" in src else src
            first = first.strip().lstrip("- ").strip()
            if first:
                return first.split("。")[0].split(".")[0][:60]
        return "Featured product"

    @staticmethod
    def _extract_key_points(body: str, text: str) -> list[str]:
        points: list[str] = []
        for src in (body, text):
            for line in src.split("\n"):
                line = line.strip().strip("- ").strip()
                if line and line not in points:
                    points.append(line)
        return points

    @staticmethod
    def _build_subtitle_text(key_points: list[str], max_len: int = 200) -> str:
        """Build a concise, human-readable subtitle from key_points.

        Not raw PPT text and not director_vision — a condensed summary
        that a human viewer can read comfortably in 5-8 seconds.
        """
        if not key_points:
            return ""
        # Take top points, deduplicate, join into readable sentences
        seen: set[str] = set()
        parts: list[str] = []
        for kp in key_points:
            # Normalize: strip leading/trailing punctuation
            kp = kp.strip().strip("-·,;:。，；：").strip()
            if not kp or kp in seen:
                continue
            seen.add(kp)
            parts.append(kp)
            if len(parts) >= 3:  # max 3 key points for subtitle
                break
        # Join with Chinese period
        text = "。".join(p.rstrip("。") for p in parts) + "。"
        # Truncate if too long
        if len(text) > max_len:
            text = text[:max_len].rstrip("。，；：") + "……"
        return text

    @staticmethod
    def available_styles() -> list[str]:
        return list(_STYLES.keys())

    @staticmethod
    def style_descriptions() -> dict[str, str]:
        return {name: s.get("aesthetic", name) for name, s in _STYLES.items()}


