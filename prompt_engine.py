# ============================================================================
# ConsistencyEngine — builds the Style Bible from slide content
# ============================================================================


class ConsistencyEngine:
    """
    Analyzes all slides and builds a :class:`ConsistencyGuide` that ensures
    every generated frame looks like it belongs to the same production.

    Steps:
    1. Infer visual style from overall content (keyword heuristics).
    2. Extract repeated characters, products, and scene keywords.
    3. Build a unified style bible.
    """

    def __init__(
        self,
        slides: list[Slide],
        style: str | dict[str, str] = "auto",
        overall_theme: str = "",
    ) -> None:
        self._slides = slides
        self._overall_theme = overall_theme

        # Resolve base style
        if isinstance(style, dict):
            self._raw_style = style
        elif style == "auto":
            self._raw_style = self._infer_style(slides)
        else:
            self._raw_style = _STYLES.get(style, _STYLES[_DEFAULT_STYLE])

    def build(self) -> ConsistencyGuide:
        """Analyze slides and produce a complete ConsistencyGuide."""
        slides = self._slides

        # --- Characters / Products ---
        characters = self._extract_characters(slides)

        # --- Settings ---
        settings = self._extract_settings(slides)

        # --- Core props / repeated elements ---
        props = self._extract_core_props(slides)

        # --- Era / theme ---
        era = self._overall_theme or "modern"

        guide = ConsistencyGuide(
            aesthetic=self._raw_style.get("aesthetic", "Professional product showcase"),
            color_palette=self._raw_style.get("colour", "Neutral warm tones"),
            lighting_scheme=self._raw_style.get("lighting", "Soft studio lighting"),
            camera_signature=self._raw_style.get("camera", "Prime lens, stable framing"),
            mood=self._raw_style.get("mood", "Professional"),
            characters=characters,
            settings=settings,
            core_props=props,
            era_or_theme=era,
            overall_theme=self._overall_theme,
        )

        logger.info(
            "ConsistencyEngine built guide: %d characters, %d settings, %d props",
            len(characters), len(settings), len(props),
        )
        return guide

    def _infer_style(self, slides: list[Slide]) -> dict[str, str]:
        """Auto-detect a visual style from slide content keywords (supports Chinese)."""
        all_text = " ".join(s.text_content for s in slides).lower()

        # --- Chinese content detection ---
        import unicodedata as _ud
