"""
Agnes vs Existing Provider — Quality Comparison Engine.

Compares images and videos generated by Agnes AI vs the current default provider
(SiliconFlow, Kling, etc.) and returns a recommendation on which is better.

Heuristic scoring factors:
  - Image: resolution, file size (proxy for detail), success rate
  - Video: resolution, duration match, file size, generation time

For robust comparison, the system generates with both providers and scores
the results automatically. The user can override the decision.
"""

from __future__ import annotations

import asyncio
import logging
import time
from dataclasses import dataclass, field
from typing import Optional

from providers.base import GenerationProvider, GenerationResult, ProviderError

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------


@dataclass
class ComparisonScore:
    """Score for a single generation result."""

    provider: str
    model: str
    resolution_score: float = 0.0  # higher resolution = better
    filesize_score: float = 0.0  # reasonable filesize = better
    success: bool = False
    generation_time: float = 0.0
    duration_match: float = 1.0  # 1.0 = perfect (video only)
    error: Optional[str] = None


@dataclass
class ComparisonResult:
    """Result of comparing two providers for the same generation task."""

    task_type: str  # "image" or "video"
    prompt: str
    winner: str  # provider name that won
    agnes_score: ComparisonScore = field(default_factory=lambda: ComparisonScore("agnes", ""))
    other_score: ComparisonScore = field(default_factory=lambda: ComparisonScore("other", ""))
    reason: str = ""


# ---------------------------------------------------------------------------
# Scoring helpers
# ---------------------------------------------------------------------------


def _score_resolution(size_str: str) -> float:
    """Score image/video resolution. Higher = better."""
    try:
        parts = size_str.lower().split("x")
        w, h = int(parts[0]), int(parts[1])
        pixels = w * h
        # 720p ~0.5, 1080p ~0.7, 2K ~0.85, 4K ~1.0
        if pixels >= 3840 * 2160:
            return 1.0
        elif pixels >= 2560 * 1440:
            return 0.85
        elif pixels >= 1920 * 1080:
            return 0.7
        elif pixels >= 1280 * 720:
            return 0.5
        else:
            return 0.3
    except (ValueError, IndexError):
        return 0.5  # unknown, assume average


def _score_filesize(data: bytes, media_type: str = "image") -> float:
    """Score file size. Too small = low quality, too large = wasteful."""
    size_kb = len(data) / 1024
    if media_type == "image":
        # Images: 50KB–500KB ideal range
        if 50 <= size_kb <= 500:
            return 1.0
        elif 10 <= size_kb <= 1000:
            return 0.7
        else:
            return 0.3
    else:
        # Videos: 100KB–50MB reasonable
        if 100 <= size_kb <= 50000:
            return 1.0
        elif 20 <= size_kb <= 100000:
            return 0.6
        else:
            return 0.2


def _is_high_quality_image(data: bytes) -> bool:
    """Quick heuristic: is this likely a high-quality image?"""
    size_kb = len(data) / 1024
    return size_kb >= 50  # Images under 50KB are often compressed/pixelated


def _is_high_quality_video(data: bytes) -> bool:
    """Quick heuristic: is this likely a good video?"""
    size_kb = len(data) / 1024
    return size_kb >= 200  # Videos under 200KB are likely very short/low quality


# ---------------------------------------------------------------------------
# Comparison engine
# ---------------------------------------------------------------------------


async def compare_image_generation(
    agnes_provider: GenerationProvider,
    other_provider: GenerationProvider,
    prompt: str,
    size: str = "1280x720",
    model_agnes: str = "",
    model_other: str = "",
) -> ComparisonResult:
    """Generate the same image with both providers and compare.

    Args:
        agnes_provider: Agnes AI provider instance.
        other_provider: The other provider (SiliconFlow, Kling, etc.).
        prompt: Image description.
        size: Output size.
        model_agnes: Agnes model name (default: agnes-image-2.1-flash).
        model_other: Other provider model name.

    Returns:
        ComparisonResult with winner and scores.
    """
    result = ComparisonResult(task_type="image", prompt=prompt, winner="agnes")

    # Try Agnes
    agnes_start = time.monotonic()
    agnes_ok = False
    try:
        agnes_res = await agnes_provider.generate_image(prompt, model=model_agnes, size=size)
        agnes_time = time.monotonic() - agnes_start
        result.agnes_score = ComparisonScore(
            provider="agnes",
            model=model_agnes or IMAGE_MODEL,
            resolution_score=_score_resolution(size),
            filesize_score=_score_filesize(agnes_res.data, "image"),
            success=True,
            generation_time=agnes_time,
        )
        agnes_ok = True
    except ProviderError as e:
        result.agnes_score.error = str(e)
        logger.warning("Agnes image generation failed: %s", e)

    # Try other provider
    other_start = time.monotonic()
    other_ok = False
    other_name = other_provider.capabilities().name
    try:
        other_res = await other_provider.generate_image(prompt, model=model_other, size=size)
        other_time = time.monotonic() - other_start
        result.other_score = ComparisonScore(
            provider=other_name,
            model=model_other or other_provider.capabilities().default_image_model,
            resolution_score=_score_resolution(size),
            filesize_score=_score_filesize(other_res.data, "image"),
            success=True,
            generation_time=other_time,
        )
        other_ok = True
    except ProviderError as e:
        result.other_score.error = str(e)
        logger.warning("%s image generation failed: %s", other_name, e)

    # Determine winner
    if agnes_ok and not other_ok:
        result.winner = "agnes"
        result.reason = "Agnes succeeded, other provider failed"
    elif other_ok and not agnes_ok:
        result.winner = other_name
        result.reason = f"{other_name} succeeded, Agnes failed"
    elif not agnes_ok and not other_ok:
        result.winner = "none"
        result.reason = "Both providers failed"
    else:
        # Both succeeded — compare scores
        agnes_total = (
            result.agnes_score.resolution_score * 0.3
            + result.agnes_score.filesize_score * 0.7
        )
        other_total = (
            result.other_score.resolution_score * 0.3
            + result.other_score.filesize_score * 0.7
        )
        if agnes_total >= other_total:
            result.winner = "agnes"
            result.reason = f"Agnes score ({agnes_total:.2f}) >= {other_name} score ({other_total:.2f})"
        else:
            result.winner = other_name
            result.reason = f"{other_name} score ({other_total:.2f}) > Agnes score ({agnes_total:.2f})"

    return result


async def compare_video_generation(
    agnes_provider: GenerationProvider,
    other_provider: GenerationProvider,
    prompt: str,
    size: str = "1280x720",
    duration: int = 5,
    image_data: Optional[bytes] = None,
    model_agnes: str = "",
    model_other: str = "",
) -> ComparisonResult:
    """Generate the same video with both providers and compare.

    Args:
        agnes_provider: Agnes AI provider instance.
        other_provider: The other provider.
        prompt: Video description.
        size: Output size.
        duration: Desired duration in seconds.
        image_data: Optional input image for image-to-video.
        model_agnes: Agnes model name.
        model_other: Other provider model name.

    Returns:
        ComparisonResult with winner and scores.
    """
    result = ComparisonResult(task_type="video", prompt=prompt, winner="agnes")

    # Try Agnes
    agnes_start = time.monotonic()
    agnes_ok = False
    try:
        agnes_res = await agnes_provider.generate_video(
            prompt, image_data=image_data, model=model_agnes, size=size, duration=duration
        )
        agnes_time = time.monotonic() - agnes_start
        agnes_duration = agnes_res.metadata.get("duration", duration)
        dur_match = 1.0 - min(abs(agnes_duration - duration) / max(duration, 1), 0.5) / 0.5
        result.agnes_score = ComparisonScore(
            provider="agnes",
            model=model_agnes or VIDEO_MODEL,
            resolution_score=_score_resolution(size),
            filesize_score=_score_filesize(agnes_res.data, "video"),
            success=True,
            generation_time=agnes_time,
            duration_match=max(0, dur_match),
        )
        agnes_ok = True
    except ProviderError as e:
        result.agnes_score.error = str(e)
        logger.warning("Agnes video generation failed: %s", e)

    # Try other provider
    other_start = time.monotonic()
    other_ok = False
    other_name = other_provider.capabilities().name
    try:
        other_res = await other_provider.generate_video(
            prompt, image_data=image_data, model=model_other, size=size, duration=duration
        )
        other_time = time.monotonic() - other_start
        other_duration = other_res.metadata.get("duration", duration)
        dur_match = 1.0 - min(abs(other_duration - duration) / max(duration, 1), 0.5) / 0.5
        result.other_score = ComparisonScore(
            provider=other_name,
            model=model_other or other_provider.capabilities().default_video_model,
            resolution_score=_score_resolution(size),
            filesize_score=_score_filesize(other_res.data, "video"),
            success=True,
            generation_time=other_time,
            duration_match=max(0, dur_match),
        )
        other_ok = True
    except ProviderError as e:
        result.other_score.error = str(e)
        logger.warning("%s video generation failed: %s", other_name, e)

    # Determine winner
    if agnes_ok and not other_ok:
        result.winner = "agnes"
        result.reason = "Agnes succeeded, other provider failed"
    elif other_ok and not agnes_ok:
        result.winner = other_name
        result.reason = f"{other_name} succeeded, Agnes failed"
    elif not agnes_ok and not other_ok:
        result.winner = "none"
        result.reason = "Both providers failed"
    else:
        agnes_total = (
            result.agnes_score.resolution_score * 0.2
            + result.agnes_score.filesize_score * 0.3
            + result.agnes_score.duration_match * 0.5
        )
        other_total = (
            result.other_score.resolution_score * 0.2
            + result.other_score.filesize_score * 0.3
            + result.other_score.duration_match * 0.5
        )
        # Speed bonus: faster = better (up to 0.1 bonus)
        if result.agnes_score.generation_time > 0 and result.other_score.generation_time > 0:
            if agnes_total >= other_total * 0.8:
                if result.agnes_score.generation_time < result.other_score.generation_time * 0.5:
                    agnes_total += 0.1
        if agnes_total >= other_total:
            result.winner = "agnes"
            result.reason = f"Agnes score ({agnes_total:.2f}) >= {other_name} score ({other_total:.2f})"
        else:
            result.winner = other_name
            result.reason = f"{other_name} score ({other_total:.2f}) > Agnes score ({agnes_total:.2f})"

    return result


# Convenience constants for import
IMAGE_MODEL = "agnes-image-2.1-flash"
VIDEO_MODEL = "agnes-video-v2.0"
TEXT_MODEL = "agnes-2.0-flash"
